#!/usr/bin/env python
"""Phase-diagram figure and macros from E07: the LMMSE floor over (rho, t) per family.

Panel (a): per-level LMMSE relative error against t for the Laplace chain, one curve per
rho (ordinal blue ramp), with t_*(rho) ticks — the floor collapses after the crossover.
Panel (b): schedule-pooled LMMSE floor against rho for the four families (categorical),
with the isotropic floor as a grey reference.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import figstyle as fs  # noqa: E402

# families whose zero-correlation cell E11 flags as unconverged on the operating grid
EXCLUDED = ("student",)


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in s).replace(".", "p")


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E07"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name or "scratch" in src.parts
    sec = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); figdir = ROOT / ("outputs/scratch/figures_dev" if dev else "paper/figures")
    sec.mkdir(parents=True, exist_ok=True); figdir.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "ladder.csv")
    # The heavy-tailed family is quoted from its recomputation on the widest domain (E07c) when
    # that run is frozen: E11 places its rho = 0 cell outside the validated envelope of the
    # operating grid (truncation, flat in N_g), and E07b/E07c measure how far widening the
    # domain moves it. The other families stay on the operating grid, where they are converged;
    # the macros record the largest movement of every pooled row between the grids.
    extra, excluded = {}, EXCLUDED
    wide, mid = ROOT / "outputs/E07c/ladder.csv", ROOT / "outputs/E07b/ladder.csv"
    if wide.exists() and mid.exists() and not dev:
        import json
        dw, dm = pd.read_csv(wide), pd.read_csv(mid)
        pw = json.loads((wide.parent / "params_ladder.json").read_text())["settings"]
        extra["phaseWideN"] = str(int(pw["grid_size"])); extra["phaseWideA"] = f"{float(pw['half_width']):g}"
        pool = lambda d: d[d.pooled.astype(bool)].groupby(["family", "rho"]).rel_lmmse.mean()
        p0, pm, pwide = pool(df), pool(dm), pool(dw)
        stu = [k for k in p0.index if k[0] in EXCLUDED]; oth = [k for k in p0.index if k[0] not in EXCLUDED]
        extra["phaseStudentMoveOperating"] = f"{float((pm[stu] - p0[stu]).abs().max()):.3f}"
        extra["phaseStudentMoveWide"] = f"{float((pwide[stu] - pm[stu]).abs().max()):.4f}"
        extra["phaseOtherMoveWide"] = f"{float((pwide[oth] - p0[oth]).abs().max()):.4f}"
        df = pd.concat([df[~df.family.isin(EXCLUDED)], dw[dw.family.isin(EXCLUDED)]], ignore_index=True)
        excluded = ()
    per = df[~df.pooled.astype(bool)].groupby(["rho", "family", "t"], as_index=False)[["rel_lmmse", "rel_iso"]].mean()
    pooled = df[df.pooled.astype(bool)].groupby(["rho", "family"], as_index=False)[["rel_lmmse", "rel_iso", "t_star", "C4", "excess_kurtosis"]].mean()
    macros = dict(extra)
    for _, r in pooled.iterrows():
        macros[f"phaseLmmse{r.family.capitalize()}Rho{_mac(f'{r.rho:g}')}"] = f"{r.rel_lmmse:.3f}"
        macros[f"phaseIso{r.family.capitalize()}Rho{_mac(f'{r.rho:g}')}"] = f"{r.rel_iso:.3f}"
        macros[f"phaseTstarRho{_mac(f'{r.rho:g}')}"] = f"{r.t_star:.2f}"
    (sec / "phase-numbers.tex").write_text("%% GENERATED by tools/make_fig_phase.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")

    fs.apply()
    fig, axes = plt.subplots(1, 2, figsize=(fs.FULL_W * 0.66, 2.0), gridspec_kw=dict(wspace=0.45))
    ax = axes[0]
    rhos = sorted(per.rho.unique())
    for i, rho in enumerate(rhos):
        d = per[(per.rho == rho) & (per.family == "laplace")].sort_values("t")
        col = fs.BLUE_RAMP[min(i, len(fs.BLUE_RAMP) - 1)]
        ax.plot(d.t, d.rel_lmmse, color=col, lw=1.3, label=f"$\\rho = {rho:g}$")
        ts = float(pooled[(pooled.rho == rho) & (pooled.family == "laplace")].t_star.iloc[0])
        if ts > 0:
            y = np.interp(ts, d.t, d.rel_lmmse); ax.plot([ts], [y], marker="|", ms=6, mew=1.1, color=col)
    ax.legend(loc="lower left", fontsize=6.5, frameon=False, handlelength=1.6, borderaxespad=0.2)
    ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlabel("diffusion time  $t$"); ax.set_ylabel("LMMSE floor, per level")
    ax.set_xticks([0.05, 0.1, 0.3, 1, 3]); ax.set_xticklabels(["0.05", "0.1", "0.3", "1", "3"])
    from matplotlib.ticker import NullFormatter
    ax.xaxis.set_minor_formatter(NullFormatter())
    fs.panel_label(ax, "(a)", x=-0.3)
    ax = axes[1]
    fams = [("laplace", "Laplace", fs.CAT[0], "-", "o"), ("bimodal", "bimodal", fs.CAT[1], "--", "s"), ("uniform", "uniform", fs.CAT[2], "-.", "^"), ("student", "Student-$t_5$", fs.CAT[3], ":", "D")]
    for key, lab, col, ls, mk in fams:
        d = pooled[pooled.family == key].sort_values("rho")
        if len(d) == 0:
            continue
        ax.plot(d.rho, d.rel_lmmse, color=col, ls=ls, marker=mk, ms=3, lw=1.3, mec=col, mfc="white" if mk in ("s", "D") else col, label=lab)
    d = pooled[pooled.family == "laplace"].sort_values("rho")
    ax.plot(d.rho, d.rel_iso, color=fs.MUTED, ls=":", lw=1.0, label="isotropic (any family)")
    ax.legend(loc="upper left", fontsize=6.5, frameon=False, handlelength=2.0, borderaxespad=0.2)
    ax.set_xlabel("correlation  $\\rho$"); ax.set_ylabel("pooled LMMSE floor"); ax.set_xlim(-0.03, 1.0)
    # E11 places the heavy-tailed family at zero correlation outside the validated quadrature
    # envelope -- essentially all of its belief mass falls outside the grid domain -- so the
    # point is drawn as excluded rather than silently plotted next to points that are not.
    # E11 places the heavy-tailed family at zero correlation outside the validated quadrature
    # envelope; the point is ringed so it cannot be read as a peer of the others, and the
    # caption says why (FIGURE_TABLE_STANDARDS F6).
    for key in excluded:
        e = pooled[(pooled.family == key) & (pooled.rho.abs() < 1e-9)]
        for _, r in e.iterrows():
            ax.plot([r.rho], [r.rel_lmmse], marker="o", ms=8.5, mfc="none", mec=fs.INK2, mew=0.8, zorder=5)
    fs.panel_label(ax, "(b)", x=-0.3)
    fs.save(fig, figdir / "fig_phase.pdf")
    print(pooled.to_string(index=False, float_format=lambda x: f"{x:.3f}")); print("wrote", figdir / "fig_phase.pdf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
