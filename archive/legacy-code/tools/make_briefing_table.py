"""The M = 2048 block of the field scoreboard, for the three-page briefing (reports/jerome-call-2026-10-19.tex).

Reads the generated paper/sections/tab-field-score.tex (tools/make_paper_numbers.py, from the frozen E33 outputs)
and keeps its header and the rows of the largest-M block, so no number is retyped. Writes
reports/field-tables/tab-field-score-2048.tex. Fails if the source layout changes (one midrule per M block).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper/sections/tab-field-score.tex"
OUT = ROOT / "reports/field-tables/tab-field-score-2048.tex"
CAPTION = (r"\caption{Risk divided by the linear floor (the Gaussian closure scores $1$) at $\nseq=2048$, mean over sixteen "
           r"seeds. The first four columns are the temperature sweep at matched correlation length, the last two refine the "
           r"base cell at fixed physical length. A dash: all sixteen fits failed. Bold: smallest in its column. The full table, "
           r"with $\nseq=128$, is in the backup, Section~B3.}")


def main() -> int:
    lines = SRC.read_text().splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == r"\midrule"]
    if len(starts) != 2:
        raise SystemExit(f"expected two M blocks in {SRC}, found {len(starts)} midrules")
    head = lines[: starts[0] + 1]
    block = lines[starts[1] + 1:]
    if not block[0].lstrip().startswith("2048 &"):
        raise SystemExit(f"second block of {SRC} does not start at M = 2048")
    out = []
    for line in head:
        if line.startswith(r"\caption{"):
            out.append(CAPTION)
        elif line.startswith(r"\label{"):
            out.append(r"\label{tab:fieldscore2048}")
        elif line.startswith(r"\begin{table*}"):
            out.append(r"\begin{table}[t]")
        else:
            out.append(line)
    tail = [r"\end{table}" if line.startswith(r"\end{table*}") else line for line in block]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("%% GENERATED by tools/make_briefing_table.py from paper/sections/tab-field-score.tex -- do not hand-edit.\n"
                   + "\n".join(out[1:] if out[0].startswith("%%") else out) + "\n" + "\n".join(tail) + "\n")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
