#!/usr/bin/env python
"""Misspecification figure and macros from E08 (predeclared analysis, registry E08.json).

Per (mechanism, eps, M): mean +/- s.e. of each arm's all-site pooled risk; the paired
per-seed ratio window / EM-BP with a seed bootstrap; break-even eps by linear
interpolation of the mean log-ratio between the two bracketing grid points (the bracket
is reported; no fitted crossing). Figure: one panel per mechanism, ratio against eps
for the two sizes, with the ratio-1 line.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import figstyle as fs  # noqa: E402
SIZE_TAG = {64: "Q", 512: "C", 2048: "D"}
# axis labels: every symbol in $...$ so the math engine sets it (FIGURE_TABLE_STANDARDS F2)
# One symbol for every strength, delta (docs/NOTATION.md: beta and gamma have other meanings)
MECH_NAME = {"global": r"rank-one latent, $\delta$", "longrange": r"long-range coupling, $\delta$",
             "ar2": r"second-lag coefficient $\delta=\rho_2$", "sitevar": r"site-varying $\rho$, amplitude $\delta$"}


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in str(s)).replace(".", "p")


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E08"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name or "scratch" in src.parts
    sec = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); figdir = ROOT / ("outputs/scratch/figures_dev" if dev else "paper/figures")
    sec.mkdir(parents=True, exist_ok=True); figdir.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "misspecification.csv"); df = df[df.region == "all"]
    piv = df.pivot_table(index=["mechanism", "eps", "n_chains", "seed"], columns="arm", values="risk").reset_index()
    macros = {}
    summ = []
    for (mech, eps, n), d in piv.groupby(["mechanism", "eps", "n_chains"]):
        rec = dict(mechanism=mech, eps=eps, n_chains=n, seeds=len(d))
        for arm in ("em_bp", "window", "lmmse_ar1", "isotropic"):
            if arm in d:
                rec[arm] = d[arm].mean(); rec[arm + "_se"] = d[arm].sem()
                macros[f"mis{_mac(mech).capitalize()}{_mac(arm).replace('_', '').capitalize()}E{_mac(eps)}{SIZE_TAG.get(n, _mac(n))}"] = f"{d[arm].mean():.3f}"
        if "window" in d and "em_bp" in d:
            r = d.window / d.em_bp; rec["ratio"] = r.mean(); rec["log_ratio"] = np.log(r).mean()
            macros[f"misRatio{_mac(mech).capitalize()}E{_mac(eps)}{SIZE_TAG.get(n, _mac(n))}"] = f"{r.mean():.2f}"
        summ.append(rec)
    summ = pd.DataFrame(summ)
    # break-even brackets
    for (mech, n), d in summ.groupby(["mechanism", "n_chains"]):
        d = d.sort_values("eps")
        if "log_ratio" not in d:
            continue
        lr = d.log_ratio.values; e = d.eps.values
        cross = [i for i in range(len(lr) - 1) if lr[i] > 0 >= lr[i + 1]]
        if cross:
            i = cross[0]; x = e[i] + (e[i + 1] - e[i]) * lr[i] / (lr[i] - lr[i + 1])
            macros[f"misBreak{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{x:.2f}"
            macros[f"misBreakLo{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{e[i]:g}"; macros[f"misBreakHi{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{e[i + 1]:g}"
        else:
            macros[f"misBreak{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = "not reached"
        # the endpoints of the swept range, so prose can name the strength a statement is made
        # at (or the strength a break-even was NOT reached by) without typing it
        macros[f"misEpsMax{_mac(mech).capitalize()}"] = f"{e[-1]:g}"
        macros[f"misEpsMin{_mac(mech).capitalize()}"] = f"{e[0]:g}"
    macros["misSeeds"] = str(int(summ.n_seeds.min())) if "n_seeds" in summ else str(int(df.seed.nunique()))
    (sec / "misspec-numbers.tex").write_text("%% GENERATED by tools/make_misspec_numbers.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(summ.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    fs.apply()
    mechs = [m for m in ("global", "longrange", "ar2", "sitevar") if m in summ.mechanism.unique()]
    # The closed-form bias of the one-view KL projection (E17) is drawn under the ratio
    # row when its frozen output exists: EM-BP's measured error at both sizes against
    # b(eps) and sqrt(b^2 + v/M). Without E17 the figure is the single ratio row.
    bias_path = ROOT / "outputs/E17/bias.csv"
    bias = pd.read_csv(bias_path) if bias_path.exists() else None
    if bias is not None:
        bias = bias[bias.eps >= 0]
    nrows = 2 if bias is not None else 1
    # One shared y-axis per row and one shared legend. Four copies of the same axis label
    # and the same two-entry legend cost four panels' worth of space and, because every
    # curve starts high on the left, put the legend on top of the data in each of them.
    # Sharing the scale also makes the four mechanisms comparable, which is the point.
    fig, axes = plt.subplots(nrows, len(mechs), figsize=(fs.FULL_W, 2.05 if nrows == 1 else 3.35),
                             sharey="row", sharex="col", gridspec_kw=dict(wspace=0.18, hspace=0.10), squeeze=False)
    handles = None
    for k, (ax, mech) in enumerate(zip(axes[0], mechs)):
        for j, n in enumerate(sorted(summ.n_chains.unique())):
            d = summ[(summ.mechanism == mech) & (summ.n_chains == n)].sort_values("eps")
            if "ratio" not in d:
                continue
            ax.plot(d.eps, d.ratio, color=fs.CAT[j], marker=fs.MARKERS[j], ms=3, lw=1.3, ls=fs.LINESTYLES[j], label=f"$M={n}$")
        ax.axhline(1.0, color=fs.MUTED, lw=0.7, ls=":")
        ax.set_yscale("log")
        if nrows == 1:
            ax.set_xlabel(MECH_NAME.get(mech, mech))
        ax.margins(x=0.08)
        if k == 0:
            ax.set_ylabel("window / EM–BP error")
            handles = ax.get_legend_handles_labels()
    # headroom above the highest point so the legend strip never reaches the curves
    top = summ.ratio.max() if "ratio" in summ else 1.0
    axes[0][0].set_ylim(top=top * 2.4)
    if bias is not None:
        for k, (ax, mech) in enumerate(zip(axes[1], mechs)):
            b = bias[bias.mechanism == mech].sort_values("eps")
            for j, n in enumerate(sorted(summ.n_chains.unique())):
                d = summ[(summ.mechanism == mech) & (summ.n_chains == n)].sort_values("eps")
                if "em_bp" not in d:
                    continue
                ax.errorbar(d.eps, d.em_bp, yerr=d.em_bp_se, color=fs.CAT[j], marker=fs.MARKERS[j], ms=3.2,
                            lw=0, elinewidth=0.8, capsize=1.5, label=f"$M={n}$")
                col = f"pred_{n}"
                if col in b and len(b):
                    ax.plot(b.eps, b[col], color=fs.CAT[j], lw=1.1, ls=fs.LINESTYLES[j],
                            label=r"$\sqrt{b^2+v/M}$" if j == 0 else None)
            if len(b):
                ax.plot(b.eps, b.bias_kl.clip(lower=1e-4), color=fs.INK2, lw=0.9, ls=(0, (1, 1.2)), label=r"$b(\delta)$")
            ax.set_yscale("log"); ax.set_xlabel(MECH_NAME.get(mech, mech)); ax.margins(x=0.08)
            if k == 0:
                ax.set_ylabel("EM–BP error")
                h, l = ax.get_legend_handles_labels()
                keep = [(hh, ll) for hh, ll in zip(h, l) if not ll.startswith("$M=")]
                ax.legend([hh for hh, _ in keep], [ll for _, ll in keep], loc="upper left", fontsize=6.5,
                          frameon=False, handlelength=2.2, borderaxespad=0.3)
        axes[1][0].set_ylim(bottom=5e-3)
    if handles and handles[0]:
        fig.legend(*handles, loc="upper center", bbox_to_anchor=(0.5, 1.04 if nrows == 2 else 1.06), ncol=2,
                   fontsize=7, frameon=False, columnspacing=1.6, handletextpad=0.5)
    fs.save(fig, figdir / "fig_misspec.pdf")
    print("wrote", figdir / "fig_misspec.pdf", f"({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
