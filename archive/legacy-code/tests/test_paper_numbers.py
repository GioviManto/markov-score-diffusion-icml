def test_cost_ratios_are_ratios_of_the_printed_medians(built):
    S = R.Sources()
    r = R.read_e24x(S)
    assert r["cmpRatioCpu"] == pytest.approx(r["cmpBpMsEightThreads"] / r["cmpTfMsEightThreads"])
    t = R.read_e47t(S)
    assert t["cmpRatioOneTf"] == pytest.approx(t["cmpBpMsOneThread"] / t["cmpTfMsOne"])
    assert t["cmpCoarseSpeedupHundred"] > t["cmpCoarseSpeedupOneFifty"] > 1.0
