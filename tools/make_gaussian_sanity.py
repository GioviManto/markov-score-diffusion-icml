#!/usr/bin/env python
"""E39's predeclared reading, its macros, and the note's figure 2 (the Gaussian sanity check).

    python tools/make_gaussian_sanity.py                                  # outputs/E39 (confirmatory)
    python tools/make_gaussian_sanity.py --src outputs/scratch/e39_quick --out outputs/scratch/e39_read   # dry run

P1  RTS against the closed form <= 1e-12 at every level.
P2  at (401, 8): grid BP against the closed form and against RTS <= 1e-10, and moment-projected BP <= 1e-10.
P3  at A = 8: non-increasing in N_g until the floor (a rise by at most 10x allowed once below 1e-12); the smallest
    N_g reaching 1e-10 at t = min is >= the one at t = max.
P4  at fixed spacing: non-increasing in A (same allowance); at A = 3 the error exceeds 1e-6 at t = min.

Writes reports/numbers/gaussian_sanity_predictions.csv, paper/sections/gaussian-sanity-numbers.tex and
paper/figures/fig_gaussian_sanity.pdf. House rules: tools/figstyle (no prose in a figure, symbols in math mode).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import figstyle as fs  # noqa: E402

FLOOR, OP_TOL, RTS_TOL = 1e-12, 1e-10, 1e-12


def monotone_to_floor(errs):
    """Non-increasing along the sweep, except that once an error is below FLOOR the next may rise by <= 10x."""
    bad = []
    for k in range(1, len(errs)):
        prev, cur = errs[k - 1], errs[k]
        if cur > prev and not (prev < FLOOR and cur <= 10 * max(prev, 1e-17)):
            bad.append(k)
    return not bad, bad


def first_below(errs, sizes, tol=OP_TOL):
    for e, n in zip(errs, sizes):
        if e <= tol:
            return int(n)
    return None


def read(d):
    rows = []
    def row(pred, clause, value, ok, note=""):
        rows.append(dict(experiment="E39", prediction=pred, clause=clause, value=value,
                         verdict="CONFIRMED" if ok else "FALSIFIED", note=note))
    g = d[(d.part == "grid") & (d.arm == "grid_bp")]
    rts = g.groupby("t").rts_vs_closed_form.max()
    row("P1", "RTS vs closed form <= 1e-12, worst level", float(rts.max()), bool((rts <= RTS_TOL).all()))
    n_op, a_op = 401, 8.0
    op = g[(g.n_grid == n_op) & (g.half_width == a_op)]
    pr = d[(d.arm == "projected") & (d.n_grid == n_op) & (d.half_width == a_op)]
    row("P2", "(401, 8) grid BP vs closed form <= 1e-10, worst level", float(op.err_closed_form.max()), bool((op.err_closed_form <= OP_TOL).all()))
    row("P2", "(401, 8) grid BP vs RTS <= 1e-10, worst level", float(op.err_rts.max()), bool((op.err_rts <= OP_TOL).all()))
    row("P2", "(401, 8) projected BP vs closed form <= 1e-10, worst level", float(pr.err_closed_form.max()) if len(pr) else np.nan,
        bool(len(pr) and (pr.err_closed_form <= OP_TOL).all()))
    ga = g[g.half_width == 8.0].sort_values("n_grid")
    mono, need = True, {}
    for t, s in ga.groupby("t"):
        ok, bad = monotone_to_floor(s.err_closed_form.tolist())
        mono &= ok
        need[t] = first_below(s.err_closed_form.tolist(), s.n_grid.tolist())
    tmin, tmax = min(need), max(need)
    row("P3", "A = 8: non-increasing in N_g to the floor at every level", float(len(need)), bool(mono))
    row("P3", "N_g reaching 1e-10: at t_min >= at t_max", float(need[tmin] or np.nan),
        bool(need[tmin] is not None and need[tmax] is not None and need[tmin] >= need[tmax]),
        f"t={tmin:g}: {need[tmin]}, t={tmax:g}: {need[tmax]}; all: " + ", ".join(f"{t:g}:{n}" for t, n in sorted(need.items())))
    dm = d[(d.part == "domain") & (d.arm == "grid_bp")].sort_values("half_width")
    mono_a = all(monotone_to_floor(s.err_closed_form.tolist())[0] for _, s in dm.groupby("t"))
    row("P4", "fixed spacing: non-increasing in A to the floor at every level", float(dm.t.nunique()), bool(mono_a))
    a3 = dm[(dm.half_width == 3.0) & (dm.t == dm.t.min())]
    row("P4", "A = 3, t_min: error > 1e-6", float(a3.err_closed_form.iloc[0]) if len(a3) else np.nan,
        bool(len(a3) and a3.err_closed_form.iloc[0] > 1e-6))
    return pd.DataFrame(rows), need


def _fmt(x):
    m, e = f"{x:.1e}".split("e")
    return f"{m}\\times10^{{{int(e)}}}"


def macros(d, need, path):
    g = d[(d.part == "grid") & (d.arm == "grid_bp")]
    op = g[(g.n_grid == 401) & (g.half_width == 8.0)]
    pr = d[(d.arm == "projected")]
    dm = d[(d.part == "domain") & (d.arm == "grid_bp")]
    a3 = dm[(dm.half_width == 3.0) & (dm.t == dm.t.min())].err_closed_form
    lines = ["% generated by tools/make_gaussian_sanity.py from outputs/E39/sanity.csv -- do not edit",
             f"\\newcommand{{\\gsRtsWorst}}{{{_fmt(g.rts_vs_closed_form.max())}}}",
             f"\\newcommand{{\\gsOpWorst}}{{{_fmt(op.err_closed_form.max())}}}",
             f"\\newcommand{{\\gsOpRtsWorst}}{{{_fmt(op.err_rts.max())}}}",
             f"\\newcommand{{\\gsProjWorst}}{{{_fmt(pr.err_closed_form.max())}}}",
             f"\\newcommand{{\\gsNeedTmin}}{{{need[min(need)]}}}",
             f"\\newcommand{{\\gsNeedTmax}}{{{need[max(need)]}}}",
             f"\\newcommand{{\\gsAthreeTmin}}{{{_fmt(a3.iloc[0]) if len(a3) else 'nan'}}}",
             f"\\newcommand{{\\gsLevels}}{{{g.t.nunique()}}}"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def figure(d, out):
    g = d[(d.part == "grid") & (d.arm == "grid_bp") & (d.half_width == 8.0)]
    dm = d[(d.part == "domain") & (d.arm == "grid_bp")]
    ts = sorted(g.t.unique())
    pick = [ts[0], ts[len(ts) // 2], ts[-1]]
    fig, axes = plt.subplots(1, 2, figsize=(fs.FULL_W, 2.35), gridspec_kw=dict(wspace=0.28))
    for ax, data, x, xl in ((axes[0], g, "n_grid", r"grid points $N_g$ ($A=8$)"),
                            (axes[1], dm, "half_width", r"half-width $A$ ($\Delta u=0.04$)")):
        for (t, c, mk) in zip(pick, (fs.CAT[0], fs.CAT[1], fs.CAT[2]), fs.MARKERS):
            s = data[data.t == t].sort_values(x)
            y = s.err_closed_form.clip(lower=1e-17)
            ax.plot(s[x], y, color=c, lw=1.0, marker=mk, ms=3.5, label=rf"$t={t:.2g}$")
            ax.plot(s[x], s.err_rts.clip(lower=1e-17), color=c, lw=0, marker="x", ms=3.5, alpha=0.8)
        floor = data.rts_vs_closed_form.max()
        ax.axhline(floor, color=fs.INK2, lw=0.8, ls=":")
        ax.set_yscale("log"); ax.set_xlabel(xl); fs.ygrid(ax)
        if x == "n_grid":
            ax.set_xscale("log")
            ax.axvline(401, color=fs.MUTED, lw=0.7, ls="--")
        else:
            ax.axvline(8, color=fs.MUTED, lw=0.7, ls="--")
    axes[0].set_ylabel(r"$\|\hat S-S\|/\|S\|$")
    axes[0].legend(loc="upper right", fontsize=6.5, handlelength=1.6, labelspacing=0.25, borderpad=0.3)
    fs.panel_label(axes[0], "(a)"); fs.panel_label(axes[1], "(b)")
    fs.save(fig, out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", default="outputs/E39")
    ap.add_argument("--out", default=None, help="dry-run directory (no paper files written)")
    a = ap.parse_args()
    d = pd.read_csv(ROOT / a.src / "sanity.csv")
    R, need = read(d)
    with pd.option_context("display.width", 220, "display.max_colwidth", 90):
        print(R.to_string(index=False))
    fs.apply()
    if a.out:
        o = ROOT / a.out; o.mkdir(parents=True, exist_ok=True)
        R.to_csv(o / "gaussian_sanity_predictions.csv", index=False, float_format="%.3g")
        macros(d, need, o / "gaussian-sanity-numbers.tex")
        figure(d, o / "fig_gaussian_sanity.pdf")
        return 0
    (ROOT / "reports/numbers").mkdir(parents=True, exist_ok=True)
    R.to_csv(ROOT / "reports/numbers/gaussian_sanity_predictions.csv", index=False, float_format="%.3g")
    macros(d, need, ROOT / "paper/sections/gaussian-sanity-numbers.tex")
    figure(d, ROOT / "paper/figures/fig_gaussian_sanity.pdf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
