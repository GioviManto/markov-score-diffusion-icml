#!/usr/bin/env python
"""Emit refinement macros from E04: how much each reported estimand moves under grid refinement.

Per (M, C) and ladder rung: mean pooled risk of EM-BP, LMMSE and isotropic; the relative
change from the production rung (401, 8) to each finer rung, max over seeds; the
reference's own movement between consecutive rungs. Macros: \refMoveEm{C}{size}{rung}
etc. with digit-free names.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SIZE_TAG = {32: "A", 128: "B", 512: "C", 2048: "D"}
RUNG_TAG = {(401, 8.0): "prod", (801, 8.0): "fine", (1601, 8.0): "finest", (801, 10.0): "wide", (201, 8.0): "coarse"}


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E04"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name
    dest = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); dest.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "refinement.csv")
    macros = {}
    base_rung = (401, 8.0) if ((df.n_grid == 401) & (df.half_width == 8.0)).any() else (int(df.n_grid.min()), 8.0)
    risk_cols = [c for c in df.columns if c.startswith("risk_")]
    for n, d in df.groupby("n_chains"):
        tag = SIZE_TAG.get(n, str(n))
        base = d[(d.n_grid == base_rung[0]) & (d.half_width == base_rung[1])].set_index("seed")
        for (ng, hw), r in d.groupby(["n_grid", "half_width"]):
            rt = RUNG_TAG.get((ng, hw), f"g{ng}a{int(hw)}")
            r = r.set_index("seed")
            for col in risk_cols:
                name = col.replace("risk_", "").replace("lmmse", "Lmmse").replace("iso", "Iso")
                if name.startswith("em_C"):
                    name = "Em" + {"1": "one", "2": "two", "4": "four", "8": "eight", "16": "sixteen"}.get(name[4:], name[4:])
                rel = ((r[col] - base[col]) / base[col]).abs()
                macros[f"refMove{name}{tag}{rt}"] = f"{100 * rel.max():.2f}"       # per cent, max over seeds
                macros[f"refMean{name}{tag}{rt}"] = f"{r[col].mean():.4f}"
            macros[f"refRefMove{tag}{rt}"] = f"{100 * r.ref_move_vs_prev.max():.3f}"
            print(f"  M={n} Ng={ng} A={hw}: " + " ".join(f"{c}={r[c].mean():.4f}(max|Δ|={100 * ((r[c] - base[c]) / base[c]).abs().max():.2f}%)" for c in risk_cols) + f"  ref move {100 * r.ref_move_vs_prev.max():.3f}%")
    macros["refSeeds"] = str(int(df.seed.nunique()))
    (dest / "refinement-numbers.tex").write_text("%% GENERATED by tools/make_refinement_numbers.py -- do not hand-edit.\n%% refMove*: max over seeds of the relative change (per cent) of the pooled risk from the production grid.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print("wrote", dest / "refinement-numbers.tex", f"({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
