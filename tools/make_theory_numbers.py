#!/usr/bin/env python
"""Emit paper/sections/theory-numbers.tex from outputs/E01 (the predeclared analysis).

Predeclared in experiments/registry/E01.json: local log-slopes per consecutive
t-interval; the asymptotic slope fitted by OLS on the levels with t >= t_* + 1 (at
rho = 0.85, t_* = 1.17, i.e. t in {3.0, 3.5, 4.0} for the shape and closure parts and
the fine grid above 2.17 for the exact Gaussian part); scaled quantities reported as
ratios to their predicted constants. Every number the theory section quotes comes from
here; nothing is typed.

Refuses to emit if the closure-gap ratio measured/predicted for the Laplace chain at
t = 3 is outside [0.8, 1.25] — that would mean the constant C_4 is wrong, and the
theory paragraph must not be typeset on top of a wrong constant.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "outputs" / "E01"
DEST = ROOT / "paper" / "sections" / "theory-numbers.tex"
T_STAR_085 = None


def _slope(t, y):
    t, y = np.asarray(t, float), np.log(np.asarray(y, float))
    return float(np.polyfit(t, y, 1)[0])


def main() -> int:
    g = pd.read_csv(SRC / "gaussian_information.csv")
    s = pd.read_csv(SRC / "shape_information.csv")
    c = pd.read_csv(SRC / "closure_gap.csv")
    cc = pd.read_csv(SRC / "closure_constants.csv").set_index("family")
    macros = {}

    # exact Gaussian chain
    for rho, d in g.groupby("rho"):
        d = d.sort_values("t")
        ts = float(d.t_star.iloc[0])
        tag = f"{rho:.2f}".replace("0.", "").replace(".", "")
        fit = d[d.t >= ts + 1.0]
        macros[f"gaussSlopeRho{tag}"] = f"{_slope(fit.t, fit.I_rho):.2f}"
        for tt in (1, 2, 3, 4):
            row = d.iloc[(d.t - tt).abs().argmin()]
            macros[f"gaussScaledRho{tag}t{tt}"] = f"{row.I_rho_scaled:.2f}"
        macros[f"gaussTstar{tag}"] = f"{ts:.2f}"
        macros[f"gaussCorrRhoQ{tag}"] = f"{d.corr_rho_q.iloc[-1]:.2f}"
    ts085 = float(g[g.rho == 0.85].t_star.iloc[0])

    # shape information: mean over replicates, then slope on t >= t_* + 1
    for beta, d in s.groupby("beta"):
        m = d.groupby("t")[["eff_rho", "eff_beta", "diag_rho", "diag_beta"]].mean().reset_index()
        fit = m[m.t >= ts085 + 1.0]
        tag = f"{beta:g}".replace(".", "p")
        macros[f"shapeSlopeBeta{tag}"] = f"{_slope(fit.t, fit.eff_beta):.2f}"
        macros[f"shapeSlopeRho{tag}"] = f"{_slope(fit.t, fit.eff_rho):.2f}"
        loc = np.diff(np.log(m.eff_beta.values)) / np.diff(m.t.values)
        macros[f"shapeLocalBeta{tag}last"] = f"{loc[-1]:.2f}"
        macros[f"shapeLocalBeta{tag}prev"] = f"{loc[-2]:.2f}"
    macros["shapeReps"] = str(int(s.rep.nunique()))
    macros["shapeChains"] = str(int(s.n_chains.iloc[0]))

    # closure gap
    for fam, d in c.groupby("family"):
        if fam == "gaussian":
            continue
        m = d.groupby("t")[["sq_gap_per_chain", "rel_lmmse", "pm_mse", "one_minus_cos", "pred_sq_gap_per_chain"]].mean().reset_index()
        fit = m[m.t >= ts085 + 1.0]
        macros[f"closureSlopeSq{fam}"] = f"{_slope(fit.t, fit.sq_gap_per_chain):.2f}"
        macros[f"closureSlopeRel{fam}"] = f"{_slope(fit.t, fit.rel_lmmse):.2f}"
        macros[f"closureSlopePm{fam}"] = f"{_slope(fit.t, fit.pm_mse):.2f}"
        macros[f"closureSlopeCos{fam}"] = f"{_slope(fit.t, fit.one_minus_cos):.2f}"
        for tt in (3.0, 3.5, 4.0):
            row = m.iloc[(m.t - tt).abs().argmin()]
            macros[f"closureRatio{fam}t{str(tt).replace('.', 'p')}"] = f"{row.sq_gap_per_chain / row.pred_sq_gap_per_chain:.2f}"
        macros[f"closureCfour{fam}"] = f"{cc.loc[fam, 'C4']:.1f}"
    lap3 = float(macros["closureRatiolaplacet3p0"])
    if not (0.8 <= lap3 <= 1.25):
        print(f"REFUSING: Laplace measured/predicted at t=3 is {lap3}; the constant C_4 does not match the data")
        return 1
    macros["closureReps"] = str(int(c.rep.nunique()))
    macros["closureChains"] = "512"

    lines = ["%% GENERATED by tools/make_theory_numbers.py from outputs/E01 -- do not hand-edit.",
             "%% Slopes: OLS of log(quantity) on t over the levels with t >= t_* + 1 (t_* = %.2f at rho = 0.85)." % ts085,
             "%% Ratios: measured / (C_4 e^{-8t}) with C_4 = ||kappa_4||_F^2 / 6."]
    for k, v in macros.items():
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(lines) + "\n")
    print(f"wrote {DEST.relative_to(ROOT)}: {len(macros)} macros")
    for k in ("gaussSlopeRho85", "shapeSlopeBeta2", "shapeSlopeBeta3", "shapeSlopeBeta1", "closureSlopeSqlaplace",
              "closureRatiolaplacet3p0", "closureRatiobimodalt4p0", "closureSlopeRellaplace"):
        print(f"  \\{k} = {macros[k]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
