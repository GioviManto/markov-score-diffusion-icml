#!/usr/bin/env python
"""Emit the generation table and macros from E05 (predeclared analysis, registry E05.json).

Per (M, arm): mean over seeds of every predeclared metric; the headline is the mean
log-likelihood gap to the reference sample under the true P_{t_min} (exact BP evidence),
with the exact arm's own gap as the sampler-discretisation floor. The step study gives
the strong error of the exact arm across nested resolutions.
Usage: make_generation_numbers.py [--src outputs/E05]; a quick/dev source writes to scratch.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SIZE_TAG = {32: "A", 128: "B", 512: "C", 2048: "D"}
ARM_TAG = {"exact": "Exact", "em_bp": "Em", "lmmse": "Lmmse", "isotropic": "Iso"}


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in s)



def _f(v, nd):
    """Format to nd decimals, normalising a negative zero."""
    t = f"{v:.{nd}f}"
    return t if float(t) != 0 else f"{0:.{nd}f}"


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E05"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name or "scratch" in src.parts
    dest = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); dest.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "generation.csv")
    metrics = ["loglik_gap", "kurt_gen", "cum4_lag_gen", "sw2", "w1_marginal", "energy", "cov_fro", "acf_err_max", "hist_kl_resid"]
    macros = {}
    g = df.groupby(["n_chains", "arm"])
    m = g[metrics + ["kurt_ref", "cum4_lag_ref", "loglik_ref"]].mean()
    se = g[metrics].sem()
    for (n, arm), r in m.iterrows():
        tag = SIZE_TAG.get(n, str(n)) + ARM_TAG.get(arm, arm.replace(":", "").replace("_", ""))
        for k in metrics:
            macros[f"gen{_mac(k.replace('_', '')).capitalize()}{tag}"] = f"{r[k]:.3f}"
        macros[f"genKurtref{SIZE_TAG.get(n, str(n))}"] = f"{r['kurt_ref']:.2f}"
    macros["genSeeds"] = str(int(df.seed.nunique())); macros["genSteps"] = str(int(df.n_steps.iloc[0]))
    steps = src / "steps.csv"
    if steps.exists():
        st = pd.read_csv(steps).sort_values("n_steps")
        for _, r in st.iterrows():
            macros[f"genStrongErr{_mac(str(int(r.n_steps)))}"] = f"{r.strong_rmse_vs_finest:.4f}"
    # table
    arms = [a for a in ("exact", "em_bp", "lmmse", "isotropic") if a in df.arm.unique()] + sorted(a for a in df.arm.unique() if a.startswith("net:"))
    lines = ["%% GENERATED by tools/make_generation_numbers.py from " + str(src.relative_to(ROOT)) + " -- do not hand-edit.",
             # six columns in one column of text: short headers, the reference sample's own
             # statistics as a row of each block rather than "(ref x)" inside every cell
             "\\begin{table}[t]\\centering\\small\\setlength{\\tabcolsep}{4pt}",
             "\\caption{Generated samples against the true law at $t_{\\min}$: mean log-likelihood gap $\\Delta\\ell$ to the reference sample under the true $P_{t_{\\min}}$ (exact evidence; the exact arm's gap is the sampler's discretisation floor), driving-noise excess kurtosis $\\hat\\kappa_4$, lag fourth cumulant, sliced $W_2$; the row marked \\emph{reference} carries the reference sample's own statistics. Mean over seeds.}",
             "\\label{tab:generation}", "\\begin{tabular}{@{}llrrrr@{}}", "\\toprule",
             "$\\nseq$ & arm & $\\Delta\\ell$ & $\\hat\\kappa_4$ & lag-$\\kappa_4$ & $W_2$ \\\\", "\\midrule"]
    for n in sorted(df.n_chains.unique()):
        first = True
        for arm in arms:
            if (n, arm) not in m.index:
                continue
            r = m.loc[(n, arm)]
            if first:
                lines.append(f"{n} & \\emph{{reference}} & -- & {_f(r.kurt_ref, 2)} & {_f(r.cum4_lag_ref, 3)} & -- \\\\")
            lines.append(f" & {arm.replace('_', '--')} & {_f(r.loglik_gap, 3)} & {_f(r.kurt_gen, 2)} & {_f(r.cum4_lag_gen, 3)} & {_f(r.sw2, 3)} \\\\")
            first = False
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\end{table}"]
    (dest / "tab-generation.tex").write_text("\n".join(lines) + "\n")
    (dest / "generation-numbers.tex").write_text("%% GENERATED by tools/make_generation_numbers.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(m[["loglik_gap", "kurt_gen", "kurt_ref", "cum4_lag_gen", "sw2", "energy"]].to_string(float_format=lambda x: f"{x:.3f}"))
    print("wrote", dest / "tab-generation.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
