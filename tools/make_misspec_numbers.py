#!/usr/bin/env python
"""Misspecification figure and macros from E08 (predeclared analysis, registry E08.json).

Per (mechanism, eps, M): mean +/- s.e. of each arm's all-site pooled risk; the paired
per-seed ratio window / EM-BP with a seed bootstrap; break-even eps by linear
interpolation of the mean log-ratio between the two bracketing grid points (the bracket
is reported; no fitted crossing). Figure: one panel per mechanism, ratio against eps
for the two sizes, with the ratio-1 line.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import figstyle as fs  # noqa: E402
SIZE_TAG = {64: "Q", 512: "C", 2048: "D"}
MECH_NAME = {"global": "rank-one latent  β", "longrange": "long-range coupling  γ", "ar2": "AR(2) coefficient  ρ₂", "sitevar": "site-varying ρ  (amplitude)"}


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in str(s)).replace(".", "p")


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E08"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name or "scratch" in src.parts
    sec = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); figdir = ROOT / ("outputs/scratch/figures_dev" if dev else "paper/figures")
    sec.mkdir(parents=True, exist_ok=True); figdir.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "misspecification.csv"); df = df[df.region == "all"]
    piv = df.pivot_table(index=["mechanism", "eps", "n_chains", "seed"], columns="arm", values="risk").reset_index()
    macros = {}
    summ = []
    for (mech, eps, n), d in piv.groupby(["mechanism", "eps", "n_chains"]):
        rec = dict(mechanism=mech, eps=eps, n_chains=n, seeds=len(d))
        for arm in ("em_bp", "window", "lmmse_ar1", "isotropic"):
            if arm in d:
                rec[arm] = d[arm].mean(); rec[arm + "_se"] = d[arm].sem()
                macros[f"mis{_mac(mech).capitalize()}{_mac(arm).replace('_', '').capitalize()}E{_mac(eps)}{SIZE_TAG.get(n, _mac(n))}"] = f"{d[arm].mean():.3f}"
        if "window" in d and "em_bp" in d:
            r = d.window / d.em_bp; rec["ratio"] = r.mean(); rec["log_ratio"] = np.log(r).mean()
            macros[f"misRatio{_mac(mech).capitalize()}E{_mac(eps)}{SIZE_TAG.get(n, _mac(n))}"] = f"{r.mean():.2f}"
        summ.append(rec)
    summ = pd.DataFrame(summ)
    # break-even brackets
    for (mech, n), d in summ.groupby(["mechanism", "n_chains"]):
        d = d.sort_values("eps")
        if "log_ratio" not in d:
            continue
        lr = d.log_ratio.values; e = d.eps.values
        cross = [i for i in range(len(lr) - 1) if lr[i] > 0 >= lr[i + 1]]
        if cross:
            i = cross[0]; x = e[i] + (e[i + 1] - e[i]) * lr[i] / (lr[i] - lr[i + 1])
            macros[f"misBreak{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{x:.2f}"
            macros[f"misBreakLo{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{e[i]:g}"; macros[f"misBreakHi{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = f"{e[i + 1]:g}"
        else:
            macros[f"misBreak{_mac(mech).capitalize()}{SIZE_TAG.get(n, _mac(n))}"] = "not reached"
    (sec / "misspec-numbers.tex").write_text("%% GENERATED by tools/make_misspec_numbers.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(summ.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    fs.apply()
    mechs = [m for m in ("global", "longrange", "ar2", "sitevar") if m in summ.mechanism.unique()]
    fig, axes = plt.subplots(1, len(mechs), figsize=(fs.FULL_W, 1.9), gridspec_kw=dict(wspace=0.4), squeeze=False)
    for ax, mech in zip(axes[0], mechs):
        for j, n in enumerate(sorted(summ.n_chains.unique())):
            d = summ[(summ.mechanism == mech) & (summ.n_chains == n)].sort_values("eps")
            if "ratio" not in d:
                continue
            ax.plot(d.eps, d.ratio, color=fs.CAT[j], marker=fs.MARKERS[j], ms=3, lw=1.3, ls=fs.LINESTYLES[j], label=f"$M={n}$")
        ax.axhline(1.0, color=fs.MUTED, lw=0.7, ls=":")
        ax.set_yscale("log"); ax.set_xlabel(MECH_NAME.get(mech, mech)); ax.set_ylabel("window / EM–BP error")
        ax.legend(loc="upper right", fontsize=7, frameon=False)
    fig.savefig(figdir / "fig_misspec.pdf"); fig.savefig(figdir / "fig_misspec.png", dpi=220)
    print("wrote", figdir / "fig_misspec.pdf", f"({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
