# ------------------------------------------------------------------------------------------------ macros
def macro_values(raw: dict) -> dict[str, str]:
    missing = sorted(set(DEFS) - set(raw))
    extra = sorted(set(raw) - set(DEFS))
    if missing or extra:
        raise SystemExit(f"make_paper_numbers: readers and DEFS disagree; undefined: {missing}; undocumented: {extra}")
    unformatted = sorted(set(DEFS) - set(FMT))
    if unformatted:
        raise SystemExit(f"make_paper_numbers: no format for {unformatted}")
    return {n: fmt(FMT[n], raw[n]) for n in sorted(DEFS)}


def macro_file(values: dict[str, str]) -> str:
    return "\n".join([HEADER, *(rf"\newcommand{{\{n}}}{{{v}}}" for n, v in values.items())]) + "\n"


def check_frozen(S: R.Sources) -> None:
    from freeze import is_frozen
    bad = sorted({f for f in S.read_files if not is_frozen(f)})
    hard = [f for f in bad if f not in UNFROZEN_ALLOWED]
    if hard:
        raise SystemExit("make_paper_numbers: the paper may read only frozen outputs (tools/freeze.py); not frozen: " + ", ".join(hard))
    for f in bad:
        print(f"WARNING: {f} is not frozen; macros that read it are only as good as an unregistered follow-up", file=sys.stderr)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def build(root: Path = ROOT):
    S = R.Sources(root)
    raw = R.read_all(S)
    values = macro_values(raw)
    tables = {name: fn(S) for name, fn in TABLES.items()}
    check_frozen(S)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["macro", "value", "source"])
    for n in sorted(values):
        _, src, stat = DEFS[n]
        w.writerow([n, values[n], f"{src}; {stat}"])
    return values, tables, buf.getvalue()


def main() -> int:
    values, tables, table_csv = build()
    write(SECTIONS / "field-numbers.tex", macro_file(values))
    for name, text in tables.items():
        write(SECTIONS / name, text)
    write(ROOT / "reports" / "numbers" / "paper_numbers.csv", table_csv)
    print(f"wrote {len(values)} macros and {len(tables)} tables")
    return 0


if __name__ == "__main__":
    sys.exit(main())
