# ------------------------------------------------------------------------------------------------ number formatting
def _dec(x) -> Decimal:
    return Decimal(repr(float(x)))


def dec(x, n: int) -> str:
    """Fixed decimals, round half up on the shortest decimal representation (so 0.2875 -> 0.29, as a person would write it)."""
    if not math.isfinite(float(x)):
        raise ValueError(f"cannot typeset {x!r}")
    q = _dec(x).quantize(Decimal(1).scaleb(-n), rounding=ROUND_HALF_UP)
    return format(q, "f")


def pct(x, n: int, signed: bool = False) -> str:
    q = (_dec(x) * 100).quantize(Decimal(1).scaleb(-n), rounding=ROUND_HALF_UP)
    s = format(q, "f")
    return ("+" if signed and q > 0 else "") + s + r"\%"


def sci(x) -> str:
    m, e = f"{float(x):.1e}".split("e")
    return f"{m}\\times10^{{{int(e)}}}"


def group(x, sep: str, step: int = 1) -> str:
    n = int((_dec(float(x) / step)).quantize(Decimal(1), rounding=ROUND_HALF_UP)) * step
    return f"{n:,}".replace(",", sep)


def fmt(spec, x) -> str:
    kind, *a = spec
    if kind == "dec":
        return dec(x, a[0])
    if kind == "pct":
        return pct(x, a[0])
    if kind == "spct":
        return pct(x, a[0], signed=True)
    if kind == "sci":
        return sci(x)
    if kind == "int":
        return dec(x, 0)
    if kind == "brace":                                # 2{,}272
        return group(x, "{,}")
    if kind == "thin":                                 # 32\,768 ; a = [step]
        return group(x, r"\,", a[0] if a else 1)
    if kind == "times":                                # 1.14\times
        return dec(x, a[0]) + r"\times"
    if kind == "text":                                 # a string typeset as text inside math: 53 of 144
        return r"\text{" + str(x) + "}"
    raise ValueError(spec)


