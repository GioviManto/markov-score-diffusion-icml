def table_score(S: R.Sources) -> str:
    T = R.score_table_data(S)
    body = [rf"$\nseq$ & estimator & {CELL_HEAD} \\", r"\midrule"]
    for m in (128, 2048):
        for i, (arm, lab) in enumerate(R.ARMS_SCORE):
            cells = []
            for c in R.ORDER:
                v, f = T["ratio"][(m, arm, c)], T["fails"][(m, arm, c)]
                if not math.isfinite(v):
                    cells.append("--")
                    continue
                best = min(T["ratio"][(m, a, c)] for a, _ in R.ARMS_SCORE if math.isfinite(T["ratio"][(m, a, c)]))
                s = dec(v, 3)
                s = rf"\textbf{{{s}}}" if v == best else s
                cells.append(s + (f"$^{{{f}}}$" if f else ""))
            body.append(f"{m if i == 0 else ''} & {lab} & " + " & ".join(cells) + r" \\")
        if m == 128:
            body.append(r"\midrule")
    n_seeds = S.csv("outputs/hpc_E33k_s*/kernels.csv").seed.nunique()
    cap = (r"Risk divided by the linear floor (a Gaussian closure scores $1$), mean over " + word(n_seeds) + r" seeds, of every estimator on the six cells; "
           r"the first four columns are the temperature sweep at matched correlation length, the last two refine the base cell at fixed physical length. "
           r"EM's stopping point and each network's checkpoint are selected by the held-out risk against the exact score. "
           r"A superscript counts failed fits, excluded from the mean; a dash means all " + word(n_seeds) + r" failed. Bold: smallest in its column.")
    return table_env(label="tab:fieldscore", caption=cap, colspec=r"@{}rlrrrrrr@{}", rows=body, star=True, tabcolsep=6.0)


