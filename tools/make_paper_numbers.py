# ------------------------------------------------------------------------------------------------ TeX plumbing
WORDS = {2: "two", 3: "three", 4: "four", 8: "eight", 9: "nine", 12: "twelve", 16: "sixteen"}


def word(n: int) -> str:
    return WORDS.get(int(n), str(int(n)))


def table_env(*, label: str, caption: str, colspec: str, rows: list[str], star: bool = False, size: str = "footnotesize", tabcolsep: float = 4.0) -> str:
    env = "table*" if star else "table"
    lines = [HEADER, rf"\begin{{{env}}}[t]", rf"\setlength{{\tabcolsep}}{{{tabcolsep:g}pt}}", r"\centering", rf"\{size}",
             rf"\caption{{{caption}}}", rf"\label{{{label}}}", rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", *rows, r"\bottomrule", r"\end{tabular}", rf"\end{{{env}}}"]
    return "\n".join(lines) + "\n"


def num(x, n: int) -> str:
    return "--" if (x is None or not math.isfinite(float(x))) else dec(x, n)


def math_num(x, n: int) -> str:
    s = num(x, n)
    return s if s == "--" or not s.startswith("-") else f"${s}$"


