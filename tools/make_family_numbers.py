#!/usr/bin/env python
"""Family figure and macros from E02b: capacity's value against the innovation's non-Gaussianity.

Per beta (excess kurtosis from +3 to -1.1 at fixed rho and variance): mean +/- s.e. over
seeds of the all-site pooled risk of EM-BP at C = 1 and C = 8, of the LMMSE oracle (the
exact price of second-order closure for that family) and of the isotropic score; the
paired C=1 minus C=8 difference with a seed bootstrap; the Hellinger distance of the
fitted C = 8 kernel to the truth. Figure: risk against excess kurtosis with the LMMSE
floor as the curve capacity is measured against.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import figstyle as fs  # noqa: E402


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in str(s)).replace(".", "p")


def boot_ci(x, n=20000, seed=20260915):
    rng = np.random.default_rng(seed); x = np.asarray(x, float)
    m = x[rng.integers(0, len(x), size=(n, len(x)))].mean(axis=1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E02b"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name
    sec = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); figdir = ROOT / ("outputs/scratch/figures_dev" if dev else "paper/figures")
    sec.mkdir(parents=True, exist_ok=True); figdir.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(src / "family.csv"); df = df[df.region == "all"]
    hcol = next((c for c in ("hellinger_weighted_mean", "hellinger_hellinger_weighted_mean") if c in df.columns), None)
    macros, rows = {}, []
    for beta, d in df.groupby("beta"):
        k4 = float(d.excess_kurtosis.iloc[0]); tag = _mac(f"{beta:g}")
        rec = dict(beta=beta, excess_kurtosis=k4)
        for arm, key in (("lmmse_true", "Lmmse"), ("isotropic", "Iso")):
            r = d[d.arm == arm].set_index("seed").risk; rec[key] = r.mean(); rec[key + "_se"] = r.sem()
            macros[f"fam{key}B{tag}"] = f"{r.mean():.3f}"
        em = {}
        for C in sorted(d[d.arm == "em_bp"].components.unique()):
            r = d[(d.arm == "em_bp") & (d.components == C)].set_index("seed").risk; em[C] = r
            rec[f"C{C}"] = r.mean(); rec[f"C{C}_se"] = r.sem()
            macros[f"famEm{_mac(C)}B{tag}"] = f"{r.mean():.3f}"; macros[f"famEm{_mac(C)}B{tag}se"] = f"{r.sem():.3f}"
            if hcol:
                macros[f"famHell{_mac(C)}B{tag}"] = f"{d[(d.arm == 'em_bp') & (d.components == C)][hcol].mean():.3f}"
            macros[f"famKurt{_mac(C)}B{tag}"] = f"{d[(d.arm == 'em_bp') & (d.components == C)].fit_kurt.mean():.2f}"
        if 1 in em and 8 in em:
            diff = (em[1] - em[8]).dropna(); lo, hi = boot_ci(diff.values)
            rec["diff"] = diff.mean(); rec["diff_lo"] = lo; rec["diff_hi"] = hi
            macros[f"famDiffB{tag}"] = f"{diff.mean():.3f}"; macros[f"famDiffB{tag}lo"] = f"{lo:.3f}"; macros[f"famDiffB{tag}hi"] = f"{hi:.3f}"
        rows.append(rec)
    summ = pd.DataFrame(rows).sort_values("excess_kurtosis")
    macros["famSeeds"] = str(int(df.seed.nunique())); macros["famSize"] = str(int(df.n_chains.iloc[0]))
    (sec / "family-numbers.tex").write_text("%% GENERATED by tools/make_family_numbers.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(summ.to_string(index=False, float_format=lambda x: f"{x:.3f}"))

    fs.apply()
    fig, ax = plt.subplots(figsize=(fs.COL_W, 2.2))
    x = summ.excess_kurtosis
    ax.plot(x, summ.Iso, color=fs.MUTED, ls=":", lw=1.0); ax.text(x.iloc[-1] + 0.15, summ.Iso.iloc[-1], "isotropic", color=fs.MUTED, fontsize=7, va="center")
    ax.plot(x, summ.Lmmse, color=fs.INK2, ls="--", lw=1.2, marker="s", ms=3, mfc="white"); ax.text(x.iloc[-1] + 0.15, summ.Lmmse.iloc[-1], "LMMSE floor", color=fs.INK2, fontsize=7, va="center")
    if "C1" in summ:
        ax.errorbar(x, summ.C1, yerr=summ.C1_se, color=fs.CAT[3], ls="-.", marker="^", ms=3.5, lw=1.3, capsize=0); ax.text(x.iloc[-1] + 0.15, summ.C1.iloc[-1], "EM–BP, $C=1$", color=fs.CAT[3], fontsize=7, va="center")
    if "C8" in summ:
        ax.errorbar(x, summ.C8, yerr=summ.C8_se, color=fs.CAT[0], ls="-", marker="o", ms=3.5, lw=1.4, capsize=0); ax.text(x.iloc[-1] + 0.15, summ.C8.iloc[-1], "EM–BP, $C=8$", color=fs.CAT[0], fontsize=7, va="center")
    ax.set_yscale("log"); ax.set_xlabel("innovation excess kurtosis  $\\kappa_4/q^2$"); ax.set_ylabel("pooled relative score error")
    ax.axvline(0, color=fs.GRID, lw=0.8); ax.set_xlim(x.min() - 0.3, x.max() + 1.4)
    fig.savefig(figdir / "fig_family.pdf"); fig.savefig(figdir / "fig_family.png", dpi=220)
    print("wrote", figdir / "fig_family.pdf", f"({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
