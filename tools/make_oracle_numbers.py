#!/usr/bin/env python
"""Emit paper/sections/oracle-numbers.tex: the oracle ladder on the variance-matched chains.

Deterministic: 512 chains per family, seed 12345, the frozen twelve-level schedule,
N_g = 401, A = 8 (docs/AUDIT_ORACLE_LADDER.md). The LMMSE oracle uses the true
covariance; by Proposition 1 it is the best any Gaussian-innovation kernel can do.
Reads nothing from experiments, so it runs anywhere in about a minute; the E02 oracle rows
(same estimator on the exp_31 test bundles) are the cross-check reported in the
capacity table.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src")); sys.path.insert(0, str(ROOT / "experiments"))
from frozen_config import FROZEN  # noqa: E402
from markov_score import theory  # noqa: E402
from markov_score.bp_grid import grid_bp_batch, make_grid  # noqa: E402
from markov_score.noising import alpha_delta  # noqa: E402
from markov_score.priors import GaussianAR1, GaussianMixtureAR1, LaplaceAR1, StudentTAR1, UniformAR1  # noqa: E402

DEST = ROOT / "paper" / "sections" / "oracle-numbers.tex"


def main() -> int:
    L, rho = FROZEN.n_sites, FROZEN.rho
    grid, w = make_grid(FROZEN.half_width, FROZEN.n_grid)
    sigma0 = theory.chain_covariance(rho, 1 - rho**2, L)
    fams = {"Laplace": LaplaceAR1(rho), "Gaussian": GaussianAR1(rho), "Student": StudentTAR1(rho, 5),
            "Uniform": UniformAR1(rho), "Bimodal": GaussianMixtureAR1(rho, 0.6)}
    rng = np.random.default_rng(12345)
    macros = {}
    for name, prior in fams.items():
        A = np.stack([prior.sample(rng, L) for _ in range(512)])
        logK = prior.log_transition_matrix(grid)
        n_lm = n_iso = den = 0.0
        per_level = []
        for t in FROZEN.t_grid:
            al, de = alpha_delta(t)
            X = al * A + np.sqrt(de) * rng.standard_normal(A.shape)
            m, _ = grid_bp_batch(grid, w, logK, X, al, de)
            s_bp = theory.score_from_mean(X, m, t)
            e_lm = ((theory.lmmse_score(X, sigma0, t) - s_bp) ** 2).sum()
            e_iso = ((theory.isotropic_score(X) - s_bp) ** 2).sum()
            en = (s_bp**2).sum()
            n_lm += e_lm; n_iso += e_iso; den += en
            per_level.append(np.sqrt(e_lm / en))
        macros[f"lmmseFloor{name}"] = f"{np.sqrt(n_lm / den):.3f}"
        macros[f"isoFloor{name}"] = f"{np.sqrt(n_iso / den):.3f}"
        macros[f"lmmseLowest{name}"] = f"{per_level[0]:.2f}"
        macros[f"lmmseHighest{name}"] = f"{per_level[-1]:.1e}"
        print(f"  {name:8s} lmmse {macros[f'lmmseFloor{name}']}  iso {macros[f'isoFloor{name}']}  lowest-level {macros[f'lmmseLowest{name}']}")
    lines = ["%% GENERATED by tools/make_oracle_numbers.py -- do not hand-edit.",
             "%% Schedule-pooled relative score error of the isotropic and LMMSE oracles against",
             "%% true-kernel grid BP, 512 chains, seed 12345, frozen configuration."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    DEST.write_text("\n".join(lines) + "\n")
    print("wrote", DEST.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
