#!/usr/bin/env python
"""Emit the baseline tables and macros from E03 (predeclared analysis, registry E03.json).

screen   -> tab-screen.tex: per architecture the winning configuration, parameter count
            range, pooled bulk risk on the dev seeds (all configurations pooled over
            seeds, sizes, restarts; the selector's own statistic).
confirm  -> tab-baselines.tex: per (M, arm) the all-site pooled risk mean +/- s.e. over the
            confirmatory seeds, with EM-BP (C = 8) from E02a and the oracles joined on
            identical (seed, size, test-bundle hash); paired per-seed ratios vs EM-BP.
matched  -> macros for the information-matched arms.
length   -> tab-length.tex: risk at L in (32, 64, 128, 256) per arm, plus EM-BP evaluated
            at those lengths by tools/eval_em_length.py (if present).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SIZE_TAG = {32: "A", 128: "B", 512: "C", 2048: "D"}
ARCH_ORDER = ["mlp", "window", "tcn", "bigru", "transformer", "unet"]
# Short forms for table headers and rows -- ten columns must fit the text width and six
# rows the column (FIGURE_TABLE_STANDARDS T2). The long forms stay in prose.
ARCH_SHORT = {"mlp": "MLP", "window": "window", "tcn": "TCN", "bigru": "bi-GRU",
              "transformer": "transf.", "unet": "U-Net", "em_bp": "EM--BP"}
ARCH_NAME = {"mlp": "MLP (global)", "window": "window head", "tcn": "dilated TCN", "bigru": "bidirectional GRU", "transformer": "transformer", "unet": "1-D U-Net", "em_bp": "EM--BP ($\\ncomp=8$)"}


def _mac(s):
    return "".join({"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven", "8": "eight", "9": "nine"}.get(c, c) for c in s).replace(":", "").replace("_", "")


def boot_ci(x, n=20000, seed=20260915):
    rng = np.random.default_rng(seed); x = np.asarray(x, float)
    m = x[rng.integers(0, len(x), size=(n, len(x)))].mean(axis=1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="outputs/E03"); ap.add_argument("--em", default="outputs/E02a/capacity.csv"); args = ap.parse_args()
    src = ROOT / args.src
    dev = "dev" in src.name or "quick" in src.name or "scratch" in src.parts
    dest = ROOT / ("outputs/scratch/sections_dev" if dev else "paper/sections"); dest.mkdir(parents=True, exist_ok=True)
    macros = {}
    # ---- screen
    sp = src / "screening.csv"
    if sp.exists():
        s = pd.read_csv(sp); s = s[s.region == "bulk"]
        g = s.groupby(["arch", "hp", "lr", "mode"]).agg(sq_err=("sq_err", "sum"), sq_ref=("sq_ref", "sum"), n_params=("n_params", "first")).reset_index()
        g["risk"] = np.sqrt(g.sq_err / g.sq_ref)
        n_dev = int(s.seed.nunique()); n_restart = int(s.restart.max()) + 1 if "restart" in s.columns else 1; n_steps = int(s.checkpoint.max()) if "checkpoint" in s.columns else 0
        budget = f"{n_dev} development seed{'s' if n_dev > 1 else ''}, two sizes and {n_restart} restart{'s' if n_restart > 1 else ''} of {n_steps:,} steps per configuration"
        lines = ["%% GENERATED by tools/make_baseline_numbers.py -- do not hand-edit.", "\\begin{table}[t]\\centering\\small",
                 "\\caption{Architecture screen under one recipe on the development seeds (never used for a reported number): the best configuration per family, its parameter count, its pooled bulk risk over " + budget + ", and the risk of the family's runner-up configuration.}",
                 "\\label{tab:screen}", "\\begin{tabular}{llrcc}", "\\toprule", "architecture & selected configuration & parameters & screen risk & runner-up \\\\", "\\midrule"]
        for arch in ARCH_ORDER:
            sub = g[g.arch == arch].sort_values("risk")
            if len(sub) == 0:
                continue
            b = sub.iloc[0]
            runner = f"{sub.iloc[1].risk:.3f}" if len(sub) > 1 else "--"
            lines.append(f"{ARCH_NAME[arch]} & {b.hp.replace('{', '').replace('}', '').replace(chr(39), '')}, lr {b.lr:g}, {b['mode']} & {int(b.n_params):,} & {b.risk:.3f} & {runner} \\\\")
            macros[f"screenRisk{_mac(arch).capitalize()}"] = f"{b.risk:.3f}"; macros[f"screenParams{_mac(arch).capitalize()}"] = f"{int(b.n_params):,}"
            if len(sub) > 1:
                macros[f"screenRunnerUp{_mac(arch).capitalize()}"] = f"{sub.iloc[1].risk:.3f}"
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        (dest / "tab-screen.tex").write_text("\n".join(lines) + "\n")
        macros["screenConfigs"] = str(int(len(g))); macros["screenDevSeeds"] = str(int(s.seed.nunique()))
    # ---- confirm
    cp = src / "confirm.csv"
    if cp.exists():
        c = pd.read_csv(cp); c = c[c.region == "all"]
        em = None
        emp = ROOT / args.em
        if emp.exists():
            e = pd.read_csv(emp); e = e[(e.region == "all")]
            em = e[(e.arm == "em_bp") & (e.components == 8)][["seed", "n_chains", "test_bundle", "risk"]].rename(columns={"risk": "risk_em"})
            orc = e[e.arm.isin(["lmmse_true", "isotropic"])].pivot_table(index=["seed", "n_chains"], columns="arm", values="risk").reset_index()
        sizes = sorted(c.n_chains.unique()); archs = [a for a in ARCH_ORDER if a in c.arch.unique()]
        # ten columns across the text width: short headers and tight column padding, at
        # \small -- fewer/shorter columns before smaller fonts (FIGURE_TABLE_STANDARDS T2)
        lines = ["%% GENERATED by tools/make_baseline_numbers.py -- do not hand-edit.",
                 "\\begin{table*}[t]\\centering\\small\\setlength{\\tabcolsep}{4.5pt}",
                 "\\caption{All-site schedule-pooled relative score error, mean over the confirmatory seeds ($\\pm$ s.e.\\ in the macros), every arm on identical test bundles. Oracles and EM--BP ($\\ncomp=8$) from the capacity experiment; networks under the common recipe with the screened configuration.}",
                 "\\label{tab:baselines}", "\\begin{tabular}{@{}r" + "c" * (2 + len(archs) + 1) + "@{}}", "\\toprule",
                 "$\\nseq$ & isotropic & LMMSE & " + " & ".join(ARCH_SHORT.get(a, ARCH_NAME[a]) for a in archs) + " & EM--BP \\\\", "\\midrule"]
        for n in sizes:
            cells = []
            if em is not None:
                o = orc[orc.n_chains == n]; cells += [f"{o.isotropic.mean():.3f}", f"{o.lmmse_true.mean():.3f}"]
                macros[f"baseIso{SIZE_TAG.get(n, str(n))}"] = f"{o.isotropic.mean():.3f}"; macros[f"baseLmmse{SIZE_TAG.get(n, str(n))}"] = f"{o.lmmse_true.mean():.3f}"
            else:
                cells += ["--", "--"]
            for a in archs:
                r = c[(c.arch == a) & (c.n_chains == n)].set_index("seed").risk
                cells.append(f"{r.mean():.3f}")
                macros[f"base{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}"] = f"{r.mean():.3f}"; macros[f"base{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}se"] = f"{r.sem():.3f}"
                if em is not None:
                    j = c[(c.arch == a) & (c.n_chains == n)].merge(em, on=["seed", "n_chains", "test_bundle"])
                    if len(j):
                        ratio = j.risk / j.risk_em; lo, hi = boot_ci(ratio.values)
                        macros[f"baseRatio{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}"] = f"{ratio.mean():.2f}"
                        macros[f"baseRatio{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}lo"] = f"{lo:.2f}"; macros[f"baseRatio{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}hi"] = f"{hi:.2f}"
                        macros[f"baseJoined{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}"] = str(int(len(j)))
            if em is not None:
                r = em[em.n_chains == n].risk_em; cells.append(f"{r.mean():.3f}")
            else:
                cells.append("--")
            lines.append(f"{n} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
        (dest / "tab-baselines.tex").write_text("\n".join(lines) + "\n")
        macros["baseSeeds"] = str(int(c.seed.nunique()))
        # at-cap rates: the fraction of confirmatory cells whose selected checkpoint is the last
        # rung of the 32k-step ladder -- the network was still improving when training stopped
        for (a, n), v in c.groupby(["arch", "n_chains"]).at_cap.mean().items():
            macros[f"baseAtCap{_mac(a).capitalize()}{SIZE_TAG.get(n, str(n))}"] = f"{100*v:.0f}"
        # The best NETWORK at each size, its paired ratio against EM-BP, and whether it is below
        # the second-order floor there. Which architecture wins changes with the sample size, so
        # the text must not name one; and the networks do cross the floor at large M
        # (docs/NEGATIVE_RESULTS.md), so the crossing is reported rather than assumed.
        for n in sizes:
            tag = SIZE_TAG.get(n, str(n))
            per = c[c.n_chains == n].groupby("arch").risk.mean().sort_values()
            if not len(per):
                continue
            best_a = per.index[0]
            macros[f"baseBestArch{tag}"] = ARCH_NAME.get(best_a, best_a)
            macros[f"baseBest{tag}"] = f"{per.iloc[0]:.3f}"
            macros[f"baseWorst{tag}"] = f"{per.iloc[-1]:.3f}"
            macros[f"baseWorstArch{tag}"] = ARCH_NAME.get(per.index[-1], per.index[-1])
            if len(per) > 1:
                macros[f"baseSecondArch{tag}"] = ARCH_NAME.get(per.index[1], per.index[1])
                macros[f"baseSecond{tag}"] = f"{per.iloc[1]:.3f}"
            if em is not None:
                fl = float(orc[orc.n_chains == n].lmmse_true.mean())
                below = [ARCH_NAME.get(a, a) for a in per.index if per.loc[a] < fl]
                macros[f"baseBelowFloorN{tag}"] = str(len(below))
                macros[f"baseBelowFloor{tag}"] = ", ".join(below) if below else "none"
                j = c[(c.arch == best_a) & (c.n_chains == n)].merge(em, on=["seed", "n_chains", "test_bundle"])
                if len(j):
                    ratio = j.risk / j.risk_em; lo, hi = boot_ci(ratio.values)
                    macros[f"baseRatioBest{tag}"] = f"{ratio.mean():.2f}"
                    macros[f"baseRatioBest{tag}lo"] = f"{lo:.2f}"; macros[f"baseRatioBest{tag}hi"] = f"{hi:.2f}"
                    macros[f"baseWinsBest{tag}"] = str(int((ratio > 1).sum()))
        print(c.groupby(["n_chains", "arch"]).risk.agg(["mean", "sem", "count"]).to_string(float_format=lambda x: f"{x:.4f}"))
    # ---- matched
    mp = src / "matched.csv"
    if mp.exists():
        m = pd.read_csv(mp); m = m[m.region == "all"]
        for (n, arm, arch), r in m.groupby(["n_chains", "arm", "arch"]).risk.agg(["mean", "sem"]).iterrows():
            macros[f"matched{_mac(arm).capitalize()}{_mac(arch).capitalize()}{SIZE_TAG.get(n, str(n))}"] = f"{r['mean']:.3f}"
        print(m.groupby(["n_chains", "arm", "arch"]).risk.agg(["mean", "sem"]).to_string(float_format=lambda x: f"{x:.4f}"))
        # The comparison the paper turns on is the arm at EM-BP's own information interface: implicit
        # score matching on one noised view per sequence, no clean chain, checkpoint selected on the
        # implicit objective of a held-out noisy bundle (interface C). The one-corruption DSM arm sees
        # the clean chain as a regression target (interface B) and is reported separately as
        # `matchedFixed*` -- it was the headline until the 18 September audit, mislabelled as matched.
        for n in sorted(m.n_chains.unique()):
            tag = SIZE_TAG.get(n, str(n))
            for arm, prefix in (("ism_one_view", "matchedBest"), ("dsm_one_corruption", "matchedFixed")):
                sub = m[(m.n_chains == n) & (m.arm == arm)].groupby("arch").risk.mean().sort_values()
                if not len(sub):
                    continue
                arch, best = sub.index[0], sub.iloc[0]
                macros[f"{prefix}{tag}"] = f"{best:.3f}"
                macros[f"{prefix}Arch{tag}"] = ARCH_NAME.get(arch, arch)
                if em is not None:
                    j = m[(m.n_chains == n) & (m.arm == arm) & (m.arch == arch)].merge(em, on=["seed", "n_chains", "test_bundle"])
                    if len(j):
                        ratio = j.risk / j.risk_em; lo, hi = boot_ci(ratio.values)
                        macros[f"{prefix.replace('Best', 'RatioBest').replace('Fixed', 'FixedRatio')}{tag}"] = f"{ratio.mean():.1f}"
                        macros[f"{prefix.replace('Best', 'RatioBest').replace('Fixed', 'FixedRatio')}{tag}lo"] = f"{lo:.1f}"
                        macros[f"{prefix.replace('Best', 'RatioBest').replace('Fixed', 'FixedRatio')}{tag}hi"] = f"{hi:.1f}"
                        macros[f"{prefix.replace('Best', 'Wins').replace('Fixed', 'FixedWins')}{tag}"] = str(int((ratio > 1).sum()))
                        macros[f"{prefix.replace('Best', 'RatioOfMeans').replace('Fixed', 'FixedRatioOfMeans')}{tag}"] = f"{j.risk.mean()/j.risk_em.mean():.1f}"
        macros["matchedBestArm"] = "implicit score matching on one noised view per sequence"
        macros["matchedFixedArm"] = "one fixed corruption of a clean sequence"
    # ---- length
    lp = src / "length.csv"
    if lp.exists():
        l = pd.read_csv(lp)
        # EM-BP evaluated at the same lengths (tools/eval_em_length.py), so the structured arm
        # appears in the same table as the networks it is compared against
        emlen = src / "em_length.csv"
        if emlen.exists():
            l = pd.concat([l, pd.read_csv(emlen)], ignore_index=True)
        g = l.groupby(["arch", "n_chains", "L_test"]).risk.agg(["mean", "sem"]).reset_index()
        lines = ["%% GENERATED by tools/make_baseline_numbers.py -- do not hand-edit.", "\\begin{table}[t]\\centering\\small\\setlength{\\tabcolsep}{4pt}",
                 "\\caption{Length extrapolation at $\\nseq=2048$: pooled relative score error of estimators fitted at $\\nsites=32$ and evaluated against the tree-exact score of longer chains, mean over $\\baseSeeds$ seeds. Longer chains are slightly easier (proportionally fewer boundary sites), so a length-agnostic arm should improve a little; the transformer instead breaks down beyond its training length.}", "\\label{tab:length}",
                 "\\begin{tabular}{@{}l" + "c" * l.L_test.nunique() + "@{}}", "\\toprule", "arm & " + " & ".join(f"$\\nsites={int(x)}$" for x in sorted(l.L_test.unique())) + " \\\\", "\\midrule"]
        big = int(max(sizes)) if sizes else int(g.n_chains.max())
        for (arch, n), sub in g.groupby(["arch", "n_chains"]):
            sub = sub.sort_values("L_test")
            if n == big:   # the table shows the largest size; every size is in the macros and the CSV
                lines.append(f"{ARCH_SHORT.get(arch, ARCH_NAME.get(arch, arch))} & " + " & ".join(f"{v:.3f}" for v in sub["mean"]) + " \\\\")
            for _, r in sub.iterrows():
                macros[f"len{_mac(arch).capitalize()}{SIZE_TAG.get(n, str(n))}L{_mac(str(int(r.L_test)))}"] = f"{r['mean']:.3f}"
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        (dest / "tab-length.tex").write_text("\n".join(lines) + "\n")
    (dest / "baseline-numbers.tex").write_text("%% GENERATED by tools/make_baseline_numbers.py -- do not hand-edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print("wrote", dest, f"({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
